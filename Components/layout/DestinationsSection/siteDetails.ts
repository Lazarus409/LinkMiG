export function siteSlug(name: string) {
  return name
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[’']/g, "-")
    .replace(/&/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}
